'use strict';

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const tempo = require('../lib/horizontal-tempo.ts');
const deck = require('../lib/phrase-deck.ts');
const cue = require('../lib/tuner-lock.ts');
const pulse = require('../lib/pulse-math.ts');

const read = (rel) => fs.readFileSync(path.join(__dirname, '..', rel), 'utf8');

assert(tempo.horizontalBpmFromDrag(20, 400, false) === 20, '20 is a hard stop');
assert(tempo.horizontalBpmFromDrag(400, -400, false) === 400, '400 is a hard stop');
assert(tempo.horizontalBpmFromDrag(120, 0, false) === 120, 'touch down does not jump BPM');
assert(tempo.horizontalBpmFromDrag(120, 28, false) === 119, 'drag right lowers one BPM');
assert(tempo.horizontalBpmFromDrag(119, -28, false) === 120, 'reversing the drag returns the BPM');
assert(tempo.horizontalBpmFromDrag(120, 14, false) === 120, 'a half step does not skip');
const fast = -1200;
assert(tempo.horizontalTrackDrag(20, [{ x: -250, v: fast }]) >= 120, 'a fast swipe can move 20 to 120');
assert(tempo.horizontalTrackDrag(120, [{ x: -450, v: fast }]) >= 300, 'a fast swipe can move 120 to 300');
assert(tempo.horizontalTrackDrag(300, [{ x: -250, v: fast }]) === 400, 'a fast swipe can move 300 to 400');
assert(tempo.horizontalTrackDrag(120, [{ x: -28, v: -40 }]) === 121, 'a slow finger raises one BPM');
assert(tempo.horizontalTrackDrag(120, [{ x: 28, v: 40 }]) === 119, 'a slow finger lowers one BPM');
assert(tempo.horizontalTrackDrag(120, [{ x: 0, v: fast }]) === 120, 'grabbing the roller does not jump');
assert(tempo.horizontalTrackDrag(120, [{ x: -28, v: -40 }, { x: -28, v: fast }]) === 121, 'release velocity does not keep turning the roller');
assert(tempo.horizontalPxPerBpm(0) === 28, 'a resting finger stays on the fine scale');
assert(tempo.horizontalPxPerBpm(1200) === 2.5, 'a fast finger uses the broad scale');
assert(tempo.horizontalPxPerBpm(800) < tempo.horizontalPxPerBpm(400), 'gain changes continuously with speed');
const slow7 = tempo.horizontalRollerPose(120, [{ x: -7, v: 0 }]);
const slow14 = tempo.horizontalRollerPose(120, [{ x: -14, v: 0 }]);
const slow28 = tempo.horizontalRollerPose(120, [{ x: -28, v: 0 }]);
assert(Math.abs(slow7.roller - 120.25) < 0.02, '7 px rolls the cylinder a quarter BPM');
assert(slow7.bpm === 120 && slow7.crossings === 0, 'a quarter BPM does not change the integer');
assert(Math.abs(slow14.roller - 120.5) < 0.02 && slow14.roller > slow7.roller, '14 px rolls farther');
assert(slow14.bpm === 120 && slow14.crossings === 0, 'a half BPM does not change the integer');
assert(slow28.bpm === 121 && slow28.crossings === 1, 'one full BPM crosses one detent');
assert(tempo.horizontalRollerPose(120, [{ x: -56, v: 0 }]).crossings === 2, 'each integer crossing is one haptic');
const toothRest = tempo.cylinderRidge(120, 120, 280);
const toothQuarter = tempo.cylinderRidge(120, slow7.roller, 280);
assert(toothRest && toothQuarter && toothQuarter.x < toothRest.x, 'fractional travel moves the knurl');
const blocked = tempo.horizontalRollerPose(20, [{ x: 80, v: 0 }, { x: 52, v: 0 }]);
assert(blocked.bpm === 21 && blocked.roller > 20, 'reversing off 20 responds immediately');
const stuffed = tempo.horizontalRollerPose(20, [{ x: 40, v: 0 }, { x: 200, v: 0 }]);
assert(stuffed.roller === 20 && stuffed.bpm === 20 && stuffed.crossings === 0, 'pushing on 20 does not store hidden travel');
const unwind = tempo.horizontalRollerPose(20, [{ x: 400, v: 0 }, { x: 393, v: 0 }]);
assert(Math.abs(unwind.roller - 20.25) < 0.02 && unwind.bpm === 20 && unwind.crossings === 0, 'the first pixels off 20 move the roller');
assert(tempo.horizontalRollerPose(400, [{ x: -90, v: -2000 }]).crossings === 0, 'pushing on 400 does not tick');
const regrab = tempo.horizontalAdvanceBpm(slow7.roller, slow7.bpm, 0, 0, false);
assert(Math.abs(regrab.roller - slow7.roller) < 1e-9 && regrab.bpm === 120, 'a new grab does not jump the roller');
const at120 = tempo.cylinderRidge(120, 120, 280);
const at123 = tempo.cylinderRidge(120, 123, 280);
assert(at120 && at123 && at123.x < at120.x, 'the same tooth rolls when BPM changes');
assert(Math.abs(at120.x - 140) < 2, 'the current BPM tooth sits on the center index');
assert(tempo.cylinderRidge(120, 200, 280) === null, 'a distant tooth is occluded by the cylinder cheek');

let state = deck.createPhraseDeck();
state = deck.phrasePress(state, 'tap').deck;
state = deck.phrasePress(state, 'tap').deck;
assert(state.phase === 'ready' && state.hasTake, 'stop leaves a take');
state = deck.phrasePress(state, 'tap').deck;
assert(state.phase === 'playing', 'play is explicit');
state = deck.phrasePress(state, 'tap').deck;
assert(state.phase === 'paused', 'pause freezes playback');
state = deck.phrasePress(state, 'tap').deck;
const ended = deck.phraseFinish({ ...state, loop: false });
assert(ended.command === 'finish' && ended.deck.phase === 'ready', 'the end without loop returns to ready');
const looped = deck.phraseFinish({ ...state, loop: true });
assert(looped.command === 'restart' && looped.deck.phase === 'playing', 'loop restarts from the top');
const cleared = deck.phrasePress(ended.deck, 'clear');
assert(cleared.command === 'clear' && cleared.deck.phase === 'idle' && cleared.deck.hasTake === false, 'clear removes the take');
const replaced = deck.phrasePress(ended.deck, 'long');
assert(replaced.command === 'replace' && replaced.deck.phase === 'recording', 'hold re-records');

assert(cue.tunerCue(-50, 'flat').word.length > 0, 'flat has a cue');
assert(cue.tunerCue(-25, 'flat').trace !== cue.tunerCue(25, 'sharp').trace, 'flat and sharp traces differ');
assert(cue.tunerCue(0, 'in-tune').trace === '#3DDC7A', 'in tune is green');
assert(cue.advanceInTuneLatch(cue.createInTuneLatch(), true, 1000, 280).fire === false, 'the ding waits for dwell');
const armed = cue.advanceInTuneLatch(cue.createInTuneLatch(), true, 1000, 280).latch;
const fired = cue.advanceInTuneLatch(armed, true, 1300, 280);
assert(fired.fire === true, 'the confirmation fires once after dwell');
assert(cue.advanceInTuneLatch(fired.latch, true, 900, 280).fire === false, 'a stable in-tune pitch does not ding again');
const left = cue.advanceInTuneLatch(fired.latch, false, 1200, 280).latch;
assert(cue.advanceInTuneLatch(left, true, 1600, 280).fire === false, 're-entry still requires a new dwell');

assert(pulse.PULSE_WAVE_ORIGIN < 0.4 && pulse.PULSE_WAVE_OUTER > 1, 'pulse waves leave the center and pass the rim');
assert(pulse.pulseBeatShouldLaunch(null, 0, true) === false, 'a stopped host does not invent a wave');
assert(pulse.pulseBeatShouldLaunch(0, 1.2, true) === true, 'the first beat at index 0 still launches a wave');
assert(pulse.pulseBeatShouldLaunch(1.2, 1.2, true) === false, 'a held host does not retrigger');
assert(pulse.pulseBeatShouldLaunch(1.2, 2.4, false) === false, 'a stopped pulse does not launch');

const wheel = read('components/classic/HorizontalTempoWheel.tsx');
const hook = read('hooks/use-phrase-recorder.ts');
const tuner = read('hooks/use-tuner.ts');
const swift = read('modules/pockt-timing/ios/PocktTimingEngine.swift');
const pendulum = read('components/classic/SmartPendulumRoom.tsx');
