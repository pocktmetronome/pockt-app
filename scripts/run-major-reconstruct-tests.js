assert(wheel.includes('cancelAnimation(rollerSv)'), 'a re-grab keeps the current cylinder position');
assert(!wheel.includes('withDecay'), 'release does not flywheel');
const capsules = read('components/classic/BeatCapsuleStrip.tsx');
assert(!capsules.includes('height: side') && capsules.includes('nodeRadius') && capsules.includes('energy * 0.34'), 'beatline carriers stay seated and grow with the beat');
assert(capsules.includes('energy * 0.34'), 'the active capsule grows with the native beat');
const pro = read('components/classic/ProRoom.tsx');
assert(!pro.includes('SafeDial'), 'pro does not keep a second tempo dial');
assert(pro.split('HorizontalTempoWheel').length >= 4, 'fitted and expanded pro both use the shared wheel');
assert(!wheel.includes('setInterval'), 'the wheel has no timer');
assert(hook.includes('reclaimSession'), 'a failed playback restore is retried');
assert(hook.includes('generation.current'), 'stale recorder restores cannot clobber a newer claim');
assert(tuner.includes('playTuneConfirm'), 'in tune plays one native confirmation');
assert(swift.includes('func playTuneConfirm()'), 'the confirmation does not rebuild the session');
assert(swift.includes('tunerConfirmMuteUntil'), 'the confirmation window is ignored by pitch analysis');
assert(pendulum.includes('gestureMode.value = 2'), 'a touch on the weight owns the gesture immediately');
assert(read('components/classic/ProRoom.tsx').includes('HorizontalTempoWheel'), 'pro uses the shared wheel');
assert(read('components/classic/BeatlineRoom.tsx').includes('HorizontalTempoWheel'), 'beatline uses the shared wheel');
assert(!read('components/classic/FoundationDialRoom.tsx').includes('ClassicDialPhraseControl'), 'the recorder stays off the play row');

